// Helper to extract clean city name
function extractCityName(siteName) {
  let name = siteName.split('_')[0].split('-')[0].trim();
  // Handle Col1, Col2, Col3, etc.
  if (name.match(/^Col\d+/i)) {
    const num = name.match(/\d+/)[0];
    const sub = siteName.split('_')[1] || '';
    return `Colombo ${num.padStart(2, '0')}${sub ? ' (' + sub.split('-')[0] + ')' : ''}`;
  }
  return name;
}

