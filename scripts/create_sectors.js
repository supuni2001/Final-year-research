const sectors = RAW_ROWS.map(r => {
  const [sectorName, sectorId, siteName, lat, lon, siteId, caLabel, throughput] = r;
  let ca = '1CC';
  if (caLabel.includes('3CC')) ca = '3CC';
  else if (caLabel.includes('2CC')) ca = '2CC';

  return {
    sectorName,
    sectorId,
    siteName,
    lat,
    lon,
    siteId,
    caConfig: ca,
    caConfigLabel: caLabel,
    bbhAvgThroughput: Number(throughput) || 18.0,
    city: extractCityName(siteName),
    provider: throughput > 22 ? 'Dialog' : throughput > 19 ? 'SLT-Mobitel' : throughput > 17 ? 'Mobitel' : 'Hutch'
  };
});

